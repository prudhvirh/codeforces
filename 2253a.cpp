using namespace std;

bool isPrime(long long n) {
    if (n <= 1) return false;
    if (n <= 3) return true;
    if (n % 2 == 0 || n % 3 == 0) return false;
    for (long long i = 5; i * i <= n; i += 6) {
        if (n % i == 0 || n % (i + 2) == 0) return false;
    }
    return true;
}

void solve() {
    int n; cin >> n; n++;
    if(isPrime(1LL*n)){
        cout << "YES\n";
    }
    else{
        cout << "NO\n";
    }
}

